#!/usr/bin/env python
"""Write exact pins for the installed dependency closure of the given root packages.

Run with the interpreter of the environment to be reproduced, e.g.
    <env-python> -I tools/constraints_from_env.py big-fish nd2 tifffile pandas > constraints/py311-research.txt

Only requirements whose environment markers apply (and no extras) are followed.
Uses the standard library plus ``packaging`` if available (falls back to a
simple name parse and ignores markers otherwise).
"""

from __future__ import annotations

import importlib.metadata as md
import platform
import re
import sys


def _canon(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _requirements(dist: md.Distribution) -> list[str]:
    out = []
    for req in dist.requires or []:
        try:
            from packaging.requirements import Requirement

            r = Requirement(req)
            if r.marker is not None and not r.marker.evaluate({"extra": ""}):
                continue
            out.append(r.name)
        except ImportError:
            if ";" in req:
                continue
            out.append(re.split(r"[ <>=!~\[(;]", req, maxsplit=1)[0])
    return out


def closure(roots: list[str]) -> dict[str, str]:
    pins: dict[str, str] = {}
    todo = list(roots)
    while todo:
        name = todo.pop()
        key = _canon(name)
        if key in pins:
            continue
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            sys.exit(f"error: {name} is not installed in this environment")
        pins[key] = dist.version
        todo.extend(_requirements(dist))
    return pins


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__, file=sys.stderr)
        return 2
    pins = closure(argv)
    print(f"# Exact pins: installed dependency closure of {' '.join(argv)}")
    print(f"# Generated by tools/constraints_from_env.py with Python {platform.python_version()} ({sys.platform}).")
    print("# Use as a pip constraints file: pip install -c <this file> <packages>")
    for key in sorted(pins):
        print(f"{key}=={pins[key]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
